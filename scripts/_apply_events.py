def load(path):
    raw = open(path, 'rb').read()
    bom = raw[:3] == b'\xef\xbb\xbf'
    txt = raw[3:].decode('utf-8') if bom else raw.decode('utf-8')
    return txt, bom

def save(path, txt, bom):
    out = txt.encode('utf-8')
    if bom:
        out = b'\xef\xbb\xbf' + out
    open(path, 'wb').write(out)

