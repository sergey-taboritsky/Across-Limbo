def repl(txt, key, value):
    # key 形如 TNW_welcome_JAP_intro_text_1 / JAP_event.1.d （无 :0，与文件风格一致）
    # 允许行首缩进（tab/空格），并用 (?m) 使 ^ 匹配行首
    pat = re.compile(r'(?m)^\s*' + re.escape(key) + r'\s*:\s*"(.*?)"', re.S)
    if not pat.search(txt):
        raise SystemExit(f"[loc] 未找到键: {key}")
    # 保留原行缩进（取匹配行首空白）
    def _sub(m):
        indent = m.group(0)[:len(m.group(0)) - len(m.group(0).lstrip())]
        return indent + f'{key}: "{value}"'
    return pat.sub(_sub, txt, count=1)

